#!/usr/bin/env python3
"""Read public source facts, render docs, optionally open PRs. No product imports."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import tempfile
import time
import tomllib
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
BRANCH = 'bot/manifest-docs-sync'


def run(*args, cwd=None):
    return subprocess.check_output(args, cwd=cwd, text=True).strip()


def relative(value):
    p = PurePosixPath(value)
    if p.is_absolute() or '..' in p.parts or not p.parts:
        raise ValueError('Unsafe relative path')
    return value


def load_manifest(path):
    m = json.loads(path.read_text())
    if m['schema_version'] != 1 or m['organization'] != 'crewloom':
        raise ValueError('Unsupported manifest')
    seen = set()
    for p in m['projects']:
        if p['repository'] in seen or not re.fullmatch(r'[A-Za-z0-9_.-]+', p['repository']):
            raise ValueError('Invalid or duplicate repository')
        seen.add(p['repository'])
        if p['format'] not in ('json', 'toml') or p['ref'] != 'main':
            raise ValueError('Unreviewed source format/ref')
        for key in ('version_file', 'output'):
            relative(p[key])
        if p['output'] not in ('documentation/CREWLOOM_FACTS.md', 'docs/CREWLOOM_FACTS.md'):
            raise ValueError('Destination is not allowlisted')
        for spec in p['counts'].values():
            relative(spec.get('glob', spec.get('json_file', '')))
    return m


def release(org, repo):
    headers = {'Accept': 'application/vnd.github+json', 'User-Agent': 'crewloom-docs-sync'}
    token = os.environ.get('GITHUB_TOKEN')
    if token:
        headers['Authorization'] = f'Bearer {token}'
    request = urllib.request.Request(f'https://api.github.com/repos/{org}/{repo}/releases/latest', headers=headers)
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                value = json.load(response)
            return {'tag': value['tag_name'], 'url': value['html_url'], 'published_at': value['published_at']}
        except urllib.error.HTTPError as error:
            if error.code == 404:
                return None
            # Shared runner IPs can hit the unauthenticated rate limit; retry transient errors.
            if error.code in (403, 429) or error.code >= 500:
                if attempt < 2:
                    time.sleep(2 * (attempt + 1))
                    continue
            raise


def collect(project, checkout, latest):
    if checkout.is_symlink():
        raise ValueError('Symlink checkout')
    def read(path):
        target = checkout / relative(path)
        if not target.resolve().is_relative_to(checkout.resolve()):
            raise ValueError('Source escapes checkout')
        return target.read_text()
    raw = read(project['version_file'])
    metadata = json.loads(raw) if project['format'] == 'json' else tomllib.loads(raw)['project']
    if not isinstance(metadata['version'], str) or not isinstance(metadata['name'], str):
        raise ValueError('Source name/version must be strings')
    counts = {}
    for name, spec in project['counts'].items():
        if 'glob' in spec:
            counts[name] = sum(1 for p in checkout.glob(spec['glob']) if p.is_file() and not p.is_symlink())
        else:
            values = json.loads(read(spec['json_file']))[spec['key']]
            if not isinstance(values, (dict, list)):
                raise ValueError('Count source must be a registry')
            counts[name] = len(values)
    return {'id': project['id'], 'repository': project['repository'],
            'source_commit': run('git', 'rev-parse', 'HEAD', cwd=checkout),
            'source_name': metadata['name'], 'source_version': metadata['version'],
            'version_file': project['version_file'], 'counts': counts, 'latest_release': latest}


def safe(value):
    return str(value).replace('|', '&#124;').replace('\n', ' ').replace('\r', ' ').replace('<', '&lt;').replace('>', '&gt;').replace('`', '&#96;')


def render(facts):
    lines = ['<!-- Generated by crewloom/.github scripts/sync-docs.py. Do not edit. -->',
             '# Crewloom source facts', '',
             'Source versions are not published versions. Counts describe files/registry entries, not quality, safety, test results or accreditation.', '',
             '| Repository | Source package | Source version | Latest stable GitHub release |',
             '| :--- | :--- | :--- | :--- |']
    for f in facts:
        tag = ('Not checked (offline preview)' if f['latest_release'] == 'offline' else
               f['latest_release']['tag'] if f['latest_release'] else 'No stable GitHub release found')
        lines.append('| ' + ' | '.join(safe(x) for x in (f['repository'], f['source_name'], f['source_version'], tag)) + ' |')
    for f in facts:
        lines += ['', f"## {safe(f['repository'])}", '',
                  f"Source: `crewloom/{safe(f['repository'])}`, `{safe(f['version_file'])}` on its manifest ref. Exact inspected commit is recorded in the workflow facts.json artifact."]
        for name, count in sorted(f['counts'].items()):
            lines.append(f'- {safe(name)}: {count}')
    lines += ['', 'Bridge naming, domains and private repository disclosures require owner decisions. No runtime, package version, license, download metadata or benchmark claim is changed by this generator.', '']
    return '\n'.join(lines)


def publish(checkout, output, content, repo):
    # Only this generated Markdown file may enter a bot commit.
    target = checkout / output
    if target.exists() and target.read_text() == content:
        return 'unchanged'
    if not target.resolve().is_relative_to(checkout.resolve()):
        raise ValueError('Destination escapes checkout')
    # Never rewrite a branch or an in-review PR. A content-addressed branch also
    # works when merged branches are retained by repository policy.
    pending = json.loads(run('gh', 'pr', 'list', '--repo', repo, '--state', 'open',
                             '--json', 'headRefName,url', cwd=checkout))
    if any(p['headRefName'].startswith(BRANCH + '-') for p in pending):
        return 'existing sync PR: skipped; review or close it first'
    branch = BRANCH + '-' + hashlib.sha256(content.encode()).hexdigest()[:12]
    if run('git', 'ls-remote', '--heads', 'origin', branch, cwd=checkout):
        return 'existing bot branch: skipped; inspect previous PR before retrying'
    run('git', 'switch', '-c', branch, cwd=checkout)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
    run('git', 'add', '--', output, cwd=checkout)
    changed = run('git', 'diff', '--cached', '--name-only', cwd=checkout).splitlines()
    if changed != [output]:
        raise ValueError('Refusing changes outside generated document')
    run('git', '-c', 'user.name=crewloom-bot', '-c', 'user.email=41898282+github-actions[bot]@users.noreply.github.com',
        'commit', '-m', 'docs: sync source facts from central manifest', cwd=checkout)
    run('git', 'push', 'origin', branch, cwd=checkout)
    return run('gh', 'pr', 'create', '--repo', repo, '--base', 'main', '--head', branch,
               '--title', 'docs: sync source facts from central manifest', '--body',
               'Generated documentation only. Source versions and stable GitHub releases remain distinct. Counts are structural, not benchmark claims. Human review and merge required. No runtime, license, publish or deployment changes.', cwd=checkout)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=ROOT / 'crewloom-manifest.json')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'sync-output')
    parser.add_argument('--checkouts', type=Path, help='Use existing read-only checkouts for offline tests')
    parser.add_argument('--offline', action='store_true', help='Skip release lookup; never publish offline output')
    parser.add_argument('--publish', action='store_true', help='Open docs-only PRs with scoped GH_TOKEN')
    args = parser.parse_args()
    if args.publish and (args.offline or args.checkouts):
        parser.error('Publishing requires fresh checkouts and live release lookup')
    m = load_manifest(args.manifest)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        sources = args.checkouts or Path(temporary)
        facts = []
        for p in m['projects']:
            checkout = sources / p['repository']
            if not args.checkouts:
                run('git', '-c', 'core.hooksPath=/dev/null', 'clone', '--depth', '1', '--branch', p['ref'],
                    f"https://github.com/{m['organization']}/{p['repository']}.git", str(checkout))
            facts.append(collect(p, checkout, 'offline' if args.offline else release(m['organization'], p['repository'])))
        # Collect everything successfully before any writes or disclosures.
        content = render(facts)
        (args.output_dir / 'facts.json').write_text(json.dumps({'schema_version': 1, 'projects': facts}, indent=2) + '\n')
        (args.output_dir / 'CREWLOOM_FACTS.md').write_text(content)
        results = []
        for p in m['projects']:
            repo = f"{m['organization']}/{p['repository']}"
            result = publish(sources / p['repository'], p['output'], content, repo) if args.publish else 'preview only'
            results.append({'repository': repo, 'result': result})
        print(json.dumps(results, indent=2))


if __name__ == '__main__':
    main()
